"""Read a saved Processing model (.model3) back into steps, so it can be reviewed and
tweaked in the same window as a recording, then saved again.

Each step of the model becomes a Step whose inputs are its fixed values. Links get
stand-in sources ("souschef-…") that the planner connects again; layer inputs and asked
settings become choices (names, help texts, "ask when the model runs").

Models made with Sous Chef open fully. Models using things this window can't
edit (expressions, conditional branches, a setting shared by several steps, …) open
view-only, with the reason.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field

from qgis.core import Qgis, QgsApplication, QgsExpression, QgsProcessing, QgsProcessingModelAlgorithm

from .builder import EXPOSABLE_TYPES, FIELD_CALCULATORS, LAYER_TYPES, PLUGINS_NOTE, Choices
from .history import Step

GEOMETRY_PREFIX = {QgsProcessing.SourceType.TypeVectorPoint: "Point", QgsProcessing.SourceType.TypeVectorLine: "LineString",
                   QgsProcessing.SourceType.TypeVectorPolygon: "Polygon"}


@dataclass
class OpenedModel:
    path: str
    name: str
    group: str
    steps: list
    choices: Choices
    snapshot: dict                      # stand-in source -> (source, name)
    read_only: str = ""                 # why the model can't be saved from the review window
    warnings: list = field(default_factory=list)
    icon: str = ""                      # an SVG symbol kept next to the model


def _kind(source) -> str:
    kinds = {Qgis.ProcessingModelChildParameterSource.ModelParameter: "param",
             Qgis.ProcessingModelChildParameterSource.ChildOutput: "child",
             Qgis.ProcessingModelChildParameterSource.StaticValue: "static"}
    return kinds.get(source.source(), "other")


def _style_file(child, model_path):
    """For a 'Set layer style' step made by Sous Chef: the .qml file it uses."""
    sources = child.parameterSources().get("STYLE", [])
    if len(sources) != 1:
        return ""
    s = sources[0]
    if _kind(s) == "static":
        return str(s.staticValue() or "")
    text = s.expression() if hasattr(s, "expression") else ""
    match = re.search(r"@model_folder\s*\|\|\s*'([^']+)'", text or "")
    if match:
        return os.path.normpath(os.path.dirname(model_path) + match.group(1))
    return ""


def _parse_formula(text, params):
    """Read back an expression made by builder.formula_expression: text pieces joined with
    '"' || @column_setting || '"'. Returns (formula with the default columns,
    [(column, setting name)] asked, {settings used}) or None when it's some other expression."""
    tokens = re.findall(r"\s*(?:'((?:[^']|'')*)'|@(\w+))\s*(\|\||$)", text or "")
    if not tokens or "".join(t[2] for t in tokens).count("||") != len(tokens) - 1:
        return None
    formula, asked, used = "", [], set()
    for literal, pname, _sep in tokens:
        if pname:
            pdef = params.get(pname)
            if pdef is None:
                return None
            default = str(pdef.defaultValue() or "")
            used.add(pname)
            if pdef.type() == "field":
                asked.append((default, pname))
            formula += default
        else:
            formula += literal.replace("''", "'")
    if QgsExpression(formula).hasParserError():
        return None
    return formula, asked, used


def open_model(path: str) -> OpenedModel:
    model = QgsProcessingModelAlgorithm()
    if not model.fromFile(path):
        raise ValueError("This file could not be read as a Processing model.")
    model.setSourceFilePath(path)
    help_content = dict(model.helpContent() or {})
    choices = Choices()
    description = help_content.get("ALG_DESC", "") or ""
    # notes Sous Chef adds itself are made again when saving
    description = "\n\n".join(p for p in description.split("\n\n") if not p.startswith(PLUGINS_NOTE)
                              and not p.startswith("Generated by Sous Chef"))
    choices.description = description.strip()
    opened = OpenedModel(path, model.name(), model.group(), [], choices, {})
    problems = []
    children = model.childAlgorithms()

    # 'Set layer style' steps made by Sous Chef become "keeps its style" on their output
    style_of = {}
    style_children = set()
    for cid, child in children.items():
        if child.algorithmId() != "native:setlayerstyle":
            continue
        inputs = child.parameterSources().get("INPUT", [])
        qml = _style_file(child, path)
        if len(inputs) == 1 and _kind(inputs[0]) == "child" and qml:
            style_of[(inputs[0].outputChildId(), inputs[0].outputName())] = qml
            style_children.add(cid)

    # steps in an order where each comes after the steps it uses
    deps = {}
    for cid, child in children.items():
        if cid in style_children:
            continue
        deps[cid] = {s.outputChildId() for sources in child.parameterSources().values() for s in sources
                     if _kind(s) == "child"}
    order, done = [], set()
    while len(order) < len(deps):
        ready = sorted((c for c in deps if c not in done and deps[c] <= done | (set(children) - set(deps))),
                       key=lambda c: (children[c].position().x(), children[c].position().y()))
        if not ready:
            problems.append("its steps depend on each other in a loop")
            ready = [c for c in deps if c not in done][:1]
        for c in ready:
            order.append(c)
            done.add(c)

    entry_of = {cid: i for i, cid in enumerate(order, start=1)}
    param_users = {}
    formula_params = set()   # model parameters used inside Field Calculator expressions
    params = {d.name(): d for d in model.parameterDefinitions() if not d.isDestination()}

    def stand_in_input(name):
        d = params.get(name)
        types = list(d.dataTypes()) if d is not None and hasattr(d, "dataTypes") else []
        prefix = GEOMETRY_PREFIX.get(types[0]) if len(types) == 1 else None
        value = f"{prefix}?souschef-input={name}" if prefix else f"souschef-input:{name}"
        opened.snapshot[value] = (value, d.description() if d is not None else name)
        return value

    for cid in order:
        child = children[cid]
        entry = entry_of[cid]
        # a fresh copy: the model's own one is freed with the model
        alg = QgsApplication.processingRegistry().createAlgorithmById(child.algorithmId())
        if alg is None:
            problems.append(f"the tool {child.algorithmId()} isn't available (is its plugin installed?)")
            continue
        if not child.isActive():
            problems.append(f"step '{child.description()}' is switched off")
        inputs, results, style_files = {}, {}, {}
        for d in alg.parameterDefinitions():
            name = d.name()
            if d.isDestination():
                continue
            sources = child.parameterSources().get(name, [])
            if not sources:
                continue
            values = []
            for s in sources:
                kind = _kind(s)
                if kind == "static":
                    values.append(s.staticValue())
                elif kind == "child":
                    stand_in = f"souschef-child:{s.outputChildId()}:{s.outputName()}"
                    values.append(stand_in)
                    if d.type() not in LAYER_TYPES and d.type() != "extent":
                        problems.append(f"'{d.description()}' of '{child.description()}' comes from another step")
                elif kind == "param":
                    pname = s.parameterName()
                    pdef = params.get(pname)
                    if d.type() in LAYER_TYPES or d.type() == "extent":
                        values.append(stand_in_input(pname))
                        uid_value = values[-1]
                        layer_uid = "layer:" + uid_value
                        choices.names[layer_uid] = pdef.description() if pdef else pname
                        choices.helps[layer_uid] = _help_text(help_content, pname, pdef)
                    else:
                        param_users.setdefault(pname, []).append((entry, name, child.algorithmId()))
                        values.append(pdef.defaultValue() if pdef is not None else None)
                        uid = f"set:{entry}:{name}"
                        choices.ask.add((entry, name))
                        choices.names[uid] = pdef.description() if pdef else pname
                        choices.helps[uid] = _help_text(help_content, pname, pdef)
                        if d.type() not in EXPOSABLE_TYPES:
                            problems.append(f"the setting '{d.description()}' can't be asked for in this window")
                else:
                    parsed = None
                    if child.algorithmId() in FIELD_CALCULATORS and name == "FORMULA":
                        parsed = _parse_formula(s.expression() if hasattr(s, "expression") else "", params)
                    if parsed is None:
                        problems.append(f"'{d.description()}' of '{child.description()}' uses an expression or a "
                                        "calculated value")
                        values.append(None)
                        continue
                    # an expression Sous Chef puts together when the model runs (asked columns)
                    formula, asked_columns, referenced = parsed
                    values.append(formula)
                    formula_params.update(referenced)
                    for col, pname in asked_columns:
                        uid = f"set:{entry}:FORMULA#{col}"
                        pdef = params.get(pname)
                        choices.ask.add((entry, f"FORMULA#{col}"))
                        choices.names[uid] = pdef.description() if pdef else pname
                        choices.helps[uid] = _help_text(help_content, pname, pdef)
            inputs[name] = values if (d.type() == "multilayer" or len(values) > 1) else values[0]
        model_outputs = {output.childOutputName(): output for output in child.modelOutputs().values()}
        for d in alg.destinationParameterDefinitions():
            inputs[d.name()] = "TEMPORARY_OUTPUT"   # as a recorded run lists it
        for d in alg.destinationParameterDefinitions():
            stand_in = f"souschef-child:{cid}:{d.name()}"
            results[d.name()] = stand_in
            uid = f"out:{entry}:{d.name()}"
            out = model_outputs.get(d.name())
            label = out.name() if out is not None else d.description()
            opened.snapshot[stand_in] = (stand_in, label)
            if out is not None:
                choices.roles[uid] = "final"
                choices.names[uid] = out.name()
                default = out.defaultValue()
                if isinstance(default, str) and default:
                    inputs[d.name()] = default
            else:
                choices.roles[uid] = "intermediate"
            if (cid, d.name()) in style_of:
                style_files[d.name()] = style_of[(cid, d.name())]
            else:
                choices.unstyled.add(uid)
        step = Step(entry, None, child.algorithmId(), inputs, results, alg)
        step.opened = {"style_files": style_files, "child_id": cid, "description": child.description()}
        note = child.comment().description() if child.comment() is not None else ""
        if note:
            choices.notes[entry] = note
        opened.steps.append(step)

    for pname, users in param_users.items():
        if len(users) < 2:
            continue
        makers = [u for u in users if u[1] == "FIELD_NAME" and u[2] in FIELD_CALCULATORS]
        if len(makers) == 1:
            # an asked new-column name that later steps' columns follow: only the name is asked
            for entry, name, _alg in users:
                if (entry, name, _alg) not in makers:
                    choices.ask.discard((entry, name))
                    choices.names.pop(f"set:{entry}:{name}", None)
        else:
            problems.append(f"the setting '{params[pname].description()}' is used by {len(users)} steps")
    used = ({v.split("=", 1)[-1].split(":", 1)[-1] for v in opened.snapshot if "souschef-input" in v}
            | set(param_users) | formula_params)
    unused = [d.description() for n, d in params.items() if n not in used]
    if unused:
        opened.warnings.append("Not used by any step, so left out when saved: " + ", ".join(unused) + ".")
    if problems:
        opened.read_only = ("This recipe can be viewed but not saved from here, because "
                            + "; ".join(dict.fromkeys(problems)) + ". Use the Model Designer to change it.")
    icon = os.path.splitext(path)[0] + ".svg"
    opened.icon = icon if os.path.isfile(icon) else ""
    return opened


def _help_text(help_content: dict, name: str, definition) -> str:
    """A parameter's help: from the model's help, otherwise the parameter's own."""
    own = definition.help() if definition is not None and hasattr(definition, "help") else ""
    return help_content.get(name) or own or ""
